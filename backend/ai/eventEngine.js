/**
 * 2. EVENT ENGINE EVENT EMITTER
 */
export class EventEngineEventEmitter {
  constructor(onEventCallback = null) {
    this.onEventCallback = onEventCallback;
    this.history = [];
  }

  emit(eventType, message, payload = null) {
    const event = {
      type: eventType,
      timestamp: new Date().toISOString(),
      message,
      ...(payload && { payload })
    };
    this.history.push(event);
    logger.info(`Event Engine Event [${eventType}]: ${message}`);

    if (typeof this.onEventCallback === 'function') {
      this.onEventCallback(event);
    }
  }
}

